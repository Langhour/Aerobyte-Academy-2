export function getCourseLocalized(course, field) {
  if (!course) return ''
  if (locale.value === 'kh') {
    const khField = `${field}_kh`
    if (course[khField] !== undefined && course[khField] !== null && String(course[khField]).trim() !== '') {
      return course[khField]
    }
    const orig = course[field]
    if (typeof orig === 'string' && khmerTranslations[orig]) {
      return khmerTranslations[orig]
    }
  }
  return course[field] || ''
}

export function getCourseBadges(course) {
  if (!course) return []
  if (locale.value === 'kh' && Array.isArray(course.badges_kh) && course.badges_kh.length > 0) {
    return course.badges_kh
  }
  if (locale.value === 'kh' && Array.isArray(course.badges)) {
    return course.badges.map((b) => khmerTranslations[b] || b)
  }
  return course.badges || []
}

