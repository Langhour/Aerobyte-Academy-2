export function useLanguage() {
  const isKhmer = computed(() => locale.value === 'kh')

  function t(englishText) {
    return isKhmer.value ? khmerTranslations[englishText] || englishText : englishText
  }

  function setLocale(value) {
    locale.value = value === 'kh' ? 'kh' : 'en'
    document.documentElement.lang = locale.value
    try {
      localStorage.setItem(storageKey, locale.value)
    } catch (error) {
      console.error('Could not save language preference:', error)
    }
  }

  return {
    locale,
    isKhmer,
    t,
    setLocale,
    getCourseLocalized,
    getCourseBadges,
    getModuleLocalized,
    getSpecLocalized,
    getSpecItemsLocalized,
  }
}

if (typeof document !== 'undefined') {
  document.documentElement.lang = locale.value
}

export const useI18n = useLanguage
