for course_index, course in enumerate(COURSES_DB):
    details = COURSE_DETAIL_CONTENT.get(course.slug)
    if details is None:
        continue
    course_detail_update = {
        "title_kh": details.get("title_kh") or course.title_kh,
        "short_description": details["description"],
        "short_description_kh": details.get("description_kh") or course.short_description_kh,
        "category_kh": details.get("category_kh") or course.category_kh,
        "level": details.get("level_en") or course.level or "All Levels",
        "level_kh": details.get("level_kh") or course.level_kh or "គ្រប់កម្រិត",
        "duration": details.get("duration_en") or course.duration or "45 Hours",
        "duration_kh": details.get("duration_kh") or course.duration_kh or "៤៥ ម៉ោង",
        "modules": [
            CourseModule(
                module_number=f"{module_index + 1:02}",
                title=title_en,
                title_kh=title_kh,
                description=desc_en,
                description_kh=desc_kh,
                icon_type=icon_type,
                image_url=image_url,
            )
            for module_index, (title_en, title_kh, desc_en, desc_kh, icon_type, image_url) in enumerate(details["modules"])
        ],
        "hardware_specs": [
            HardwareSpec(
                title=title_en,
                title_kh=title_kh,
                items=items_en,
                items_kh=items_kh,
            )
            for title_en, title_kh, items_en, items_kh in details["specs"]
        ],
    }
    COURSES_DB[course_index] = course.model_copy(update=course_detail_update)
