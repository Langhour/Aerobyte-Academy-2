from app.models import Course, CourseModule, HardwareSpec


def _course(
    *,
    source_id: str,
    slug: str,
    title: str,
    category: str,
    price: float,
    original_price: float,
    image: str,
    language: str = "English",
    short_description: str = "",
    duration: str | None = None,
    level: str | None = None,
    modules: list[CourseModule] | None = None,
    hardware_specs: list[HardwareSpec] | None = None,
    image_url: str | None = None,
    title_kh: str | None = None,
    short_description_kh: str | None = None,
    category_kh: str | None = None,
    level_kh: str | None = None,
    duration_kh: str | None = None,
    badges_kh: list[str] | None = None,
) -> Course:
    discount = round((1 - price / original_price) * 100) if original_price > price else 0
    return Course(
        id=f"robotx-{source_id}",
        slug=slug,
        title=title,
        short_description=short_description,
        category=category,
        section_group="Courses",
        level=level,
        price=price,
        original_price=original_price if original_price > price else None,
        discount_badge=f"{discount}% OFF" if discount else None,
        language=language,
        duration=duration,
        image_url=image_url
        or f"https://images.unsplash.com/{image}?auto=format&fit=crop&w=900&q=85",
        modules=modules or [],
        hardware_specs=hardware_specs or [],
        title_kh=title_kh,
        short_description_kh=short_description_kh,
        category_kh=category_kh,
        level_kh=level_kh,
        duration_kh=duration_kh,
        badges_kh=badges_kh or [],
    )


